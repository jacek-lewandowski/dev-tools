compose_env() {
# ---------------------------------------------------------------------------
# .env
# ---------------------------------------------------------------------------

if [ ! -f "$ENV_FILE" ]; then
    cat > "$ENV_FILE" <<'ENVEOF'
# Secrets for this sandbox. Uncomment and fill in as needed.
# ANTHROPIC_API_KEY=
# GEMINI_API_KEY=
ENVEOF
fi
chmod 600 "$ENV_FILE"

# The host's own identity, from its global git configuration: no repository is
# discovered, so a project cannot choose which identity its sandbox commits as.
HOST_GIT_NAME=$(ai_sandbox_host_git - config user.name 2>/dev/null || true)
HOST_GIT_EMAIL=$(ai_sandbox_host_git - config user.email 2>/dev/null || true)

HOST_UID="$HOST_UID" \
HOST_GID="$HOST_GID" \
HOST_USER="$HOST_USER" \
HOST_GIT_NAME="$HOST_GIT_NAME" \
HOST_GIT_EMAIL="$HOST_GIT_EMAIL" \
WITH_DOCKER="$WITH_DOCKER" \
WITH_AUDIO="$WITH_AUDIO" \
KNOWLEDGE="$KNOWLEDGE" \
PROJECT_ABS_DIR="$PROJECT_ABS_DIR" \
DISPLAY_MODE="$DISPLAY_MODE" \
DISPLAY_NUM="$NESTED_DISPLAY_NUM" \
CPUSET="$CPUSET" \
MEM_GB="$MEMORY_GB" \
KNOWLEDGE_STAMP="$AI_SANDBOX_KNOWLEDGE_STAMP" \
python3 - "$ENV_FILE" <<'PYEOF'
import os, sys
path = sys.argv[1]
managed = {
    "HOST_UID": os.environ.get("HOST_UID", ""),
    "HOST_GID": os.environ.get("HOST_GID", ""),
    "HOST_USER": os.environ.get("HOST_USER", ""),
    "HOST_GIT_NAME": os.environ.get("HOST_GIT_NAME", ""),
    "HOST_GIT_EMAIL": os.environ.get("HOST_GIT_EMAIL", ""),
    "SANDBOX_WITH_DOCKER": "1" if os.environ.get("WITH_DOCKER") == "yes" else "0",
    # 2 is a request for host audio; 1 is the old shape (read as no request,
    # never written) and 0 is off.
    "SANDBOX_WITH_AUDIO": "2" if os.environ.get("WITH_AUDIO") == "yes" else "0",
    # The knowledge stamp: the start scripts refuse a sandbox whose stamp does
    # not match the host's configuration (value and rule: ai-sandbox-lib.sh),
    # and its project dir is what the re-create command names.
    "SANDBOX_KNOWLEDGE": os.environ.get("KNOWLEDGE_STAMP", "") if os.environ.get("KNOWLEDGE") == "yes" else "0",
    "SANDBOX_PROJECT_DIR": os.environ.get("PROJECT_ABS_DIR", ""),
    "SANDBOX_DISPLAY_MODE": os.environ.get("DISPLAY_MODE", ""),
    "SANDBOX_DISPLAY_NUM": os.environ.get("DISPLAY_NUM", ""),
    "SANDBOX_CPUSET": os.environ.get("CPUSET", ""),
    # The size the start scripts count against the host's memory budget.
    "SANDBOX_MEMORY_GB": os.environ.get("MEM_GB", ""),
    # The build-caches stamp (D7): unconditional, so every sandbox this script
    # (re)creates gets the overlay caches; a sandbox not yet recreated has no
    # stamp and every caches function is a no-op for it (I8).
    "SANDBOX_BUILD_CACHES": "1",
}
MARKER = "# Managed by create-ai-sandbox.sh"
kept = [
    line for line in open(path, encoding="utf-8").read().splitlines()
    if line.split("=", 1)[0].strip() not in managed and line.strip() != MARKER
]
while kept and not kept[-1].strip():
    kept.pop()
lines = kept + ["", MARKER] + [
    f"{k}={v}" for k, v in managed.items() if v != ""
]
open(path, "w", encoding="utf-8").write("\n".join(lines) + "\n")
PYEOF

# Build-cache lowers and per-sandbox upper/work, created now (not left to
# Docker, which would make a missing bind source root-owned) and unconditional
# on --no-start, so a --no-start run gets them too. The stamp this script just
# wrote above (D7) is what makes this not a no-op (I8).
ai_sandbox_caches_prepare "$SANDBOX_DIR"
}

compose_file() {
# ---------------------------------------------------------------------------
# docker-compose.yml
# ---------------------------------------------------------------------------

step "Generating docker-compose.yml"

{
cat <<COMPOSE_HEAD
# Generated by create-ai-sandbox.sh -- edits here are overwritten on the next run.
services:
  ${CONTAINER_NAME}:
    image: "${IMAGE_NAME}"
    container_name: "${CONTAINER_NAME}"
    hostname: "${PROJECT_NAME}-sandbox"
    restart: "no"
    init: true
    shm_size: '${SHM_SIZE}'
    mem_limit: "${MEMORY_LIMIT}"
    memswap_limit: "${MEMORY_SWAP_LIMIT}"
    # Half as many cores as GB of RAM, rounded up, as a cpuset so that nproc agrees.
    cpuset: "${CPUSET}"
    # The host wins CPU under contention; no cap while it is idle.
    cpu_shares: 256
    # Under host-wide memory pressure the kernel kills a sandbox before host apps.
    oom_score_adj: 500
    # A runaway build or fork bomb cannot exhaust the host's process table
    # (threads count; IntelliJ plus Gradle uses a few hundred).
    pids_limit: 4096
    # Bridged, not host, networking: the sandbox can reach the internet but not
    # every service bound to the host's loopback. The host itself is reachable
    # by name when deliberately needed.
    extra_hosts:
      - "host.docker.internal:host-gateway"
    # Matches the real host path so Claude Code's path-keyed state
    # (~/.claude/projects/<sanitised-path>) lines up between host and sandbox.
    working_dir: "${PROJECT_ABS_DIR}"
COMPOSE_HEAD

printf '%s' "$SECURITY_OPT_BLOCK"

if [ -n "$CGROUP_LINES" ]; then
    echo "    device_cgroup_rules:"
    printf '%s' "$CGROUP_LINES"
fi
if [ -n "$DEVICE_LINES" ]; then
    echo "    devices:"
    printf '%s' "$DEVICE_LINES"
fi

cat <<COMPOSE_ENV
    environment:
      - "XDG_RUNTIME_DIR=/run/user/\${HOST_UID}"
      - "TERM=xterm-256color"
      - "CI=true"
      - "PLAYWRIGHT_HTML_REPORT=none"
      - "PYTHONPATH=${CONTAINER_HOME}"
      - "SANDBOX_WITH_DOCKER=\${SANDBOX_WITH_DOCKER}"
      - "SANDBOX_KNOWLEDGE=\${SANDBOX_KNOWLEDGE}"
      - "SANDBOX_STATUS_DIR=${AI_SANDBOX_STATUS_MOUNT}"
      # Subagents kept alive through a review/fix loop pause for minutes at a
      # time; the 5m default lets their cache expire in every pause. The env
      # var wins over settings.json, so the seeded copy cannot undo it.
      - "CLAUDE_CODE_SUBAGENT_PROMPT_CACHE_TTL=1h"
COMPOSE_ENV
# Where sandbox-knowledge-sync finds the read-only origin (the in-image command's override).
if [ "$KNOWLEDGE" = "yes" ]; then
    printf '      - "SANDBOX_KNOWLEDGE_ORIGIN=%s"\n' "$AI_SANDBOX_ORIGIN_MOUNT"
fi
printf '%s' "$DISPLAY_ENV_LINES"

# The 'idea' wrapper is baked into the shared image, so it learns the path here
# rather than having it hard-coded.
if [ -d "$IDEA_HOST_DIR" ]; then
    printf '      - "SANDBOX_IDEA_HOME=%s"\n' "$IDEA_HOST_DIR"
fi

cat <<'COMPOSE_ENVFILE'
    env_file:
      - .env
COMPOSE_ENVFILE

cat <<COMPOSE_VOLS
    volumes:
      # The project, at its real host path, read-write.
      - "${PROJECT_ABS_DIR}:${PROJECT_ABS_DIR}"
      # dev-tools helpers, read-only.
      - "${HOST_TOOLS_DIR}:${CONTAINER_HOME}/tools:ro"
      - "${HOME}/.gitignore:${CONTAINER_HOME}/.gitignore"
      # Sandbox-local copies of tool state (logins, settings, extensions).
      - "${SANDBOX_DIR}/.gemini:${CONTAINER_HOME}/.gemini"
      - "${SANDBOX_DIR}/.antigravity:${CONTAINER_HOME}/.antigravity"
      - "${SANDBOX_DIR}/.antigravity-ide:${CONTAINER_HOME}/.antigravity-ide"
      - "${SANDBOX_DIR}/.claude:${CONTAINER_HOME}/.claude"
      - "${SANDBOX_DIR}/.claude.json:${CONTAINER_HOME}/.claude.json"
      - "${SANDBOX_DIR}/.codex:${CONTAINER_HOME}/.codex"
      - "${SANDBOX_DIR}/antigravity-data:${CONTAINER_HOME}/.config/Antigravity"
      - "${SANDBOX_DIR}/antigravity-ide-data:${CONTAINER_HOME}/.config/Antigravity IDE"
      - "${SANDBOX_DIR}/claude-data:${CONTAINER_HOME}/.config/Claude"
      - "${SANDBOX_DIR}/gcloud:${CONTAINER_HOME}/.config/gcloud"
      # Per sandbox, never shared: these hold code the sandbox writes at run
      # time, and a shared copy would let one sandbox feed code to another.
      - "${SANDBOX_DIR}/cache:${CONTAINER_HOME}/.cache"
      - "${SANDBOX_DIR}/npm:${CONTAINER_HOME}/.npm"
COMPOSE_VOLS

# Build caches (docs/superpowers/specs/2026-10-02-ai-sandbox-build-caches-design.md):
# an overlay Docker volume per row of ai_sandbox_build_caches, declared under
# the top-level 'volumes:' section appended below. Host and container paths
# are identical here (CONTAINER_HOME == HOME).
while IFS='|' read -r _key _path; do
    [ -n "$_key" ] || continue
    printf '      - "%s:%s/%s"\n' "$_key" "$CONTAINER_HOME" "$_path"
done < <(ai_sandbox_build_caches)
unset _key _path

# C-STATUS: what the host reports about this sandbox, read-only, whether or not
# knowledge is configured (the host writes it; the doctor reads it).
cat <<COMPOSE_STATUS
      - "${SANDBOX_DIR}/status:${AI_SANDBOX_STATUS_MOUNT}:ro"
COMPOSE_STATUS

if [ "$KNOWLEDGE" = "yes" ]; then
cat <<COMPOSE_KNOWLEDGE
      # Shared knowledge: the rendered main branch of the knowledge repository,
      # read-only, at every path the tools read global rules and roles from.
      - "${SHARED_DIR}/knowledge/GLOBAL.md:${CONTAINER_HOME}/.gemini/GEMINI.md:ro"
      - "${SHARED_DIR}/knowledge/GLOBAL.md:${CONTAINER_HOME}/.claude/CLAUDE.md:ro"
      - "${SHARED_DIR}/knowledge/GLOBAL.md:${CONTAINER_HOME}/.codex/AGENTS.md:ro"
      - "${SHARED_DIR}/knowledge/claude/agents:${CONTAINER_HOME}/.claude/agents:ro"
      - "${SHARED_DIR}/knowledge/gemini/agents:${CONTAINER_HOME}/.gemini/agents:ro"
      - "${SHARED_DIR}/knowledge/codex/agents:${CONTAINER_HOME}/.codex/agents:ro"
      # This sandbox's own clone of the knowledge repository, read-write, on its
      # proposals branch (main for the integrator). It holds no credentials: it
      # fetches only from the read-only origin below (sandbox-knowledge-sync) and
      # never pushes; the host reads it through a confined container and does all
      # network git.
      - "${SANDBOX_DIR}/knowledge:${CONTAINER_HOME}/knowledge"
      # The origin that clone fetches from: bare, written by the host only.
      - "$(ai_sandbox_origin_dir "$SANDBOX_DIR"):${AI_SANDBOX_ORIGIN_MOUNT}:ro"
COMPOSE_KNOWLEDGE
else
cat <<COMPOSE_BRAIN
      # The shared brain: one file, read by Antigravity as GEMINI.md and by
      # Claude Code as CLAUDE.md, live on the host and in every sandbox.
      - "${HOME}/.gemini/GEMINI.md:${CONTAINER_HOME}/.gemini/GEMINI.md"
      - "${HOME}/.gemini/GEMINI.md:${CONTAINER_HOME}/.claude/CLAUDE.md"
COMPOSE_BRAIN
fi

cat <<COMPOSE_VOLS
      # Live-shared Antigravity brain and conversations. ~/.gemini/config is
      # deliberately NOT here: it holds mcp_config.json and plugins/, which the
      # host's Antigravity executes, so it is seeded per sandbox instead.
      - "${HOME}/.gemini/antigravity/brain:${CONTAINER_HOME}/.gemini/antigravity/brain"
      - "${HOME}/.gemini/antigravity/conversations:${CONTAINER_HOME}/.gemini/antigravity/conversations"
      - "${HOME}/.gemini/antigravity-ide/brain:${CONTAINER_HOME}/.gemini/antigravity-ide/brain"
      - "${HOME}/.gemini/antigravity-ide/conversations:${CONTAINER_HOME}/.gemini/antigravity-ide/conversations"
      # Live-shared Claude Code history and memory for THIS project only. The
      # whole of ~/.claude/projects would let a prompt-injected agent read other
      # projects' transcripts and plant memory the host loads automatically.
      - "${CLAUDE_PROJECT_DIR}:${CONTAINER_HOME}/.claude/projects/${CLAUDE_PROJECT_DIR##*/}"
COMPOSE_VOLS

if [ -d "$IDEA_HOST_DIR" ]; then
    echo "      # IntelliJ IDEA: the host's installation read-only, plus this"
    echo "      # sandbox's own settings and indexes. Plugins come from the"
    echo "      # shared store below."
    printf '      - "%s:%s:ro"\n' "$IDEA_HOST_DIR" "$IDEA_HOST_DIR"
    printf '      - "%s/jetbrains-config:%s/.config/JetBrains"\n' "$SANDBOX_DIR" "$CONTAINER_HOME"
    printf '      - "%s/jetbrains-cache:%s/.cache/JetBrains"\n' "$SANDBOX_DIR" "$CONTAINER_HOME"
fi

if [ -d "$HOST_SDKMAN" ]; then
    echo "      # SDKMAN: the toolchains read-only from the host, and this"
    echo "      # sandbox's own symlink farm carrying its own defaults."
    printf '      - "%s:%s:ro"\n' "$HOST_SDKMAN" "$CONTAINER_SDKMAN_HOST"
    printf '      - "%s:%s/.sdkman"\n' "$SDKMAN_FARM" "$CONTAINER_HOME"
fi

echo "      # Code shared by every sandbox, synced from the host and read-only:"
echo "      # one sandbox cannot plant code that another sandbox runs."
while IFS='|' read -r _sub _ctr _sb; do
    [ -n "$_sub" ] || continue
    printf '      - "%s/%s:%s/%s:ro"\n' "$SHARED_DIR" "$_sub" "$CONTAINER_HOME" "$_ctr"
done < <(ai_sandbox_shared_mounts)
printf '%s' "$DISPLAY_VOL_LINES"

echo "volumes:"
while IFS='|' read -r _key _path; do
    [ -n "$_key" ] || continue
    printf '  %s:\n' "$_key"
    printf '    name: "%s"\n' "$(ai_sandbox_caches_volume "$CONTAINER_NAME" "$_key")"
    echo "    driver: local"
    echo "    driver_opts:"
    echo "      type: overlay"
    echo "      device: overlay"
    printf '      o: "%s"\n' "$(ai_sandbox_caches_opts "$SANDBOX_DIR" "$_key" "$HOME/$_path")"
done < <(ai_sandbox_build_caches)
unset _key _path
} > "$COMPOSE_FILE"

log "$COMPOSE_FILE"
}
